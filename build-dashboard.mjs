import { build } from 'esbuild';
import { readFile, writeFile, rename } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(fileURLToPath(import.meta.url));
const output = path.join(root, 'public/dashboard.bundle.js');
const declared = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const installed = JSON.parse(await readFile(path.join(root, 'node_modules/esbuild/package.json'), 'utf8'));
if (declared.devDependencies.esbuild !== installed.version) {
  throw new Error('Install the pinned esbuild version before building.');
}
const result = await build({
  absWorkingDir: root,
  entryPoints: ['public/dashboard.js'],
  outfile: output,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  write: false,
  metafile: true,
  banner: { js: '// Generated by build-dashboard.mjs. Edit the source modules, then rebuild.' },
  plugins: [{
    name: 'keep-optional-panels-separate',
    setup(builder) {
      builder.onResolve({ filter: /^\.\// }, args =>
        args.kind === 'dynamic-import' ? { path: args.path, external: true } : undefined);
    },
  }],
});
if (Object.values(result.metafile.outputs).some(asset =>
  asset.imports.some(item => item.kind !== 'dynamic-import'))) {
  throw new Error('A required startup dependency was left outside the dashboard bundle.');
}
const bytes = result.outputFiles[0].contents;
if (process.argv.includes('--check')) {
  if (!Buffer.from(bytes).equals(await readFile(output))) {
    throw new Error('Dashboard bundle is stale. Run npm run build:dashboard before deployment.');
  }
  console.log('Dashboard bundle matches its source.');
} else {
  await writeFile(output + '.tmp', bytes);
  await rename(output + '.tmp', output);
  console.log(`Bundled dashboard startup (${bytes.length} bytes); optional panels load on demand.`);
}
